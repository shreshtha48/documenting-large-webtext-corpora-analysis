"""Extension of §4.2: are popular safety, bias and capability benchmarks in C4.EN?

Same measurement as the reproduction (reproduction/benchmark-contamination): exact matches over all of C4.EN via
infini-gram (a lower bound on the paper's case- and punctuation-normalised matching), Wilson CIs per field.

The design question is provenance. C4 is the April 2019 crawl (CC-MAIN-2019-18), so:
- "written after Apr 2019" fields were written for the benchmark after the crawl. They CANNOT be in C4; any match is
  a chance match of generic wording (e.g. "Who invented the Internet?"). They are the NEGATIVE CONTROL, giving the
  method's false-positive rate on short, generic text.
- "web text, before Apr 2019" fields were copied from web pages (Wikipedia, OpenWebText, WikiHow, Reddit, exam sites)
  that existed before the crawl. A match means the benchmark and C4 share a source, not that a test set leaked.
- "written before Apr 2019" fields were written for the benchmark but published before the crawl (could be online).
Positive control: the reproduction's Dodge Table 5 XSum summaries (8 of 10 found).

Each field: data/benchmarks/<field>.jsonl.gz, one {"id", "text"} per line, plus data/benchmarks/fields.json with the
metadata (benchmark, part, group, year, source). Sources are pinned where the repo allows (GitHub commits);
Hugging Face sets come from the dataset viewer's parquet export.

Usage: python scripts/build_benchmarks.py [--fields ...]
"""
