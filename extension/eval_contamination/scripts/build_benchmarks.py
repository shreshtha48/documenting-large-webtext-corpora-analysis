def csv_url(url, name):
    return pd.read_csv(B.fetch(url, name))


def detok(tokens):
    s = " ".join(tokens)
    s = re.sub(r"\s+([.,;:!?)'])", r"\1", s)
    return re.sub(r"\(\s+", "(", s).replace(" n't", "n't").replace(" 's", "'s")


def unmojibake(s):
    """A few RealToxicityPrompts texts are UTF-8 read as cp1252 ("â€™"); undo that when it applies."""
    if "â€" not in s and "Ã" not in s:
        return s
    try:
        return s.encode("cp1252").decode("utf-8")
    except (UnicodeEncodeError, UnicodeDecodeError):
        return s


def rtp_sentence(r):
    return unmojibake((r["prompt"]["text"] + r["continuation"]["text"]).strip())


