def write(field, texts):
    texts = [t for t in (str(x).strip() for x in texts) if t]
    with gzip.open(os.path.join(OUT, f"{field}.jsonl.gz"), "wt", encoding="utf-8") as g:
        for i, t in enumerate(texts):
            g.write(json.dumps({"id": i, "text": t}, ensure_ascii=False) + "\n")
    return len(texts)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fields", nargs="*", default=list(FIELDS))
    args = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)
    meta_path = os.path.join(OUT, "fields.json")
    meta = json.load(open(meta_path)) if os.path.exists(meta_path) else {}
    for f in args.fields:
        name, part, group, year, source, loader = FIELDS[f]
        try:
            n = write(f, loader())
        except Exception as e:                           # one unavailable source should not stop the others
            print(f"{f}: FAILED ({type(e).__name__}: {str(e)[:150]})", flush=True)
            continue
        meta[f] = {"benchmark": name, "part": part, "group": group, "year": year, "source": source, "texts": n}
        print(f"{f}: {n} texts", flush=True)
    json.dump(meta, open(meta_path, "w"), indent=1)


if __name__ == "__main__":
    main()
